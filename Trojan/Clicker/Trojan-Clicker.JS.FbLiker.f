                <h3 class="news-title"> Эмч нарын талийгаачид тооцож байсан хүүг сэтгэлийн тэнхээ нь хөл дээр нь босгожээ</h3>
                <div class="more-news">
                    <div class="more-left">
                        <span class="read-count" title="Уншсан тоо">5457</span><span class="comment-icon" title="Сэтгэгдэл бичсэн тоо">3</span>                    </div>
