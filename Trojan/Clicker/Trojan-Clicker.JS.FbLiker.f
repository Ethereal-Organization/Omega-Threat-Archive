                    <p style="text-align: justify;"><img src="http://status.tvmongolia.mn//news/2014/01/02/image/2.jpg" width="400" height="249" align="left" alt="" />Тархины хорт хавдрын улмаас бүх бие нь мэдээгүй болсон 14 настай хүүг эмч нар бараг л талийгаачид тооцсон байжээ. Гэтэл тэр гэнэт эдгэрч, бүр тхэквондогоор хичээллэн, хар бүсний эзэн болж эмч нарыг гайхашруулжээ.</p>
<p style="text-align: justify;">Даниэль Кимминс долоон насныхаа төрсөн өдрөөс хэдхэн өдрийн өмнө тархины хорт хавдар гэсэн оноштойгоор яаралтай тархины хагалгаанд орсон аж. Хагалгааны дараа биеийнх зүүн тал бүхэлдээ саажсан түүнийг эмч нар насан туршдаа эдгэрэхгүй, энэ хэвээрээ үлдэнэ хэмээн анхааруулсан байна.</p>
<p style="text-align: justify;">Гэвч Даниэль бууж өгсөнгүй, хэдийгээр эмч нар хүүг дахиж хөл дээрээ явж эхэлнэ гэдэгт бараг итгэлгүй байсан ч тэр бүрэн эдгэрч, зургаан настайгаасаа эхлэн сонирхох болсон тхэквондогоороо хичээллэх болжээ. Түүний ээж 47 настай Хайди &ldquo;Даниэль хагалгааны дараа зүүни тал нь мэдээгүй болсон төдийгүй ярих чадвараа алдсан байсан. Эмч нар бидэнд түүнийг алдаж ч магадгүй гэдгийг анхааруулсан. Бид түүнийг бүрэн эдгэрнэ гэдэгт найдахаа больж, насан туршдаа орондоо хадагдах байх гэж бодож байлаа. Түүний биеийн байдал тийм л хүнд байсан юм&rdquo; хэмээн ярьж байна. Гэтэл хүү бүхнийг гайхашруулж чаджээ. Хүү амьдралынхаа төлөө зүтгэж, хоёр жилийн турш хичээн сургуулласны эцэст явж бас ярьж чаддаг болсон төдийгүй хагалгаанд орохоосоо өмнө хийж байсан бүхнээ хийж чаддаг болсон байна.</p>
